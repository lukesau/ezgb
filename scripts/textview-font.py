#!/usr/bin/env python3
"""Pack the text viewer's font (docs/text-viewer.md).

Reads the DV glyph sheet (kernel/mod/font12/font12_dv.txt, Tamzen 6x12) and
writes kernel/mod/src/textview_font.h: codes $20-$7E, ten bytes each, one per
pixel row, bit 7 the leftmost pixel. Only rows 1-10 of the 12 are kept (row
11 is empty in every glyph and row 0 holds one pixel row of $ { and }), which
is what lets the viewer set its rows 10 px apart. Run after editing the sheet:

    scripts/textview-font.py
"""
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SRC = os.path.join(ROOT, "kernel", "mod", "font12", "font12_dv.txt")
OUT = os.path.join(ROOT, "kernel", "mod", "src", "textview_font.h")
TOP, ROWS, WIDTH = 1, 10, 6


def main():
    glyphs, cur = {}, None
    for line in open(SRC):
        line = line.rstrip("\n")
        m = re.match(r"glyph 0x([0-9A-Fa-f]+)", line)
        if m:
            cur = int(m.group(1), 16)
            glyphs[cur] = []
        elif cur is not None and re.fullmatch(r"[.#]{10}", line):
            glyphs[cur].append(line)
    out = ["/* Generated by scripts/textview-font.py from kernel/mod/font12/font12_dv.txt",
           " * (Tamzen 6x12, kernel/mod/font12/LICENSE-Tamzen). Do not edit. */",
           "static const u8 tv_font[95 * 10] = {"]
    for code in range(0x20, 0x7F):
        rows = glyphs[code]
        assert len(rows) == 12, hex(code)
        for r in rows[TOP:TOP + ROWS]:
            assert "#" not in r[WIDTH:], hex(code)
        vals = [sum(0x80 >> x for x in range(WIDTH) if r[x] == "#") for r in rows[TOP:TOP + ROWS]]
        name = chr(code) if code not in (0x5C,) else "backslash"
        out.append("    " + ",".join("0x%02x" % v for v in vals) + ",   /* %s */" % name)
    out.append("};")
    with open(OUT, "w") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    main()
