/* 00:155a: draw glyph ch of wFont8x12 with its top left at x, y */
void PlotGlyph12 (UINT8 ch, UINT8 x, UINT8 y) __banked
{
	UINT8 i;
	UINT16 base;
	UINT8 b;

	base = ch * 12;
	for (i = 0; i < 12; i++) {
		b = wFont8x12[base + i];
		if (b & 0x01) plot_point(x + 7, y);
		if (b & 0x02) plot_point(x + 6, y);
		if (b & 0x04) plot_point(x + 5, y);
		if (b & 0x08) plot_point(x + 4, y);
		if (b & 0x10) plot_point(x + 3, y);
		if (b & 0x20) plot_point(x + 2, y);
		if (b & 0x40) plot_point(x + 1, y);
		if (b & 0x80) plot_point(x, y);
		y++;
	}
}
